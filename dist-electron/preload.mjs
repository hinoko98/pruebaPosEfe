"use strict";
const electron = require("electron");
electron.contextBridge.exposeInMainWorld("api", {
  login: (payload) => electron.ipcRenderer.invoke("auth:login", payload),
  createUser: (payload) => electron.ipcRenderer.invoke("auth:createUser", payload),
  logout: () => electron.ipcRenderer.invoke("auth:logout"),
  listProducts: () => electron.ipcRenderer.invoke("products:list"),
  createSale: (payload) => electron.ipcRenderer.invoke("sales:create", payload),
  getDashboardStats: (range) => electron.ipcRenderer.invoke("dashboard:stats", range),
  getCorrespondentCatalog: () => electron.ipcRenderer.invoke("correspondent:catalog"),
  getCorrespondentDashboard: () => electron.ipcRenderer.invoke("correspondent:dashboard"),
  listCorrespondentTransactions: (payload) => electron.ipcRenderer.invoke("correspondent:transactions:list", payload),
  createCorrespondentTransaction: (payload) => electron.ipcRenderer.invoke("correspondent:transaction:create", payload),
  listCorrespondentClosures: (payload) => electron.ipcRenderer.invoke("correspondent:closures:list", payload),
  createCorrespondentClosure: (payload) => electron.ipcRenderer.invoke("correspondent:closure:create", payload),
  getAppStatus: () => electron.ipcRenderer.invoke("app:status"),
  getBusinessSettings: () => electron.ipcRenderer.invoke("settings:get"),
  updateBusinessSettings: (payload) => electron.ipcRenderer.invoke("settings:update", payload),
  getCashSummary: () => electron.ipcRenderer.invoke("cash:summary"),
  openCashSession: (payload) => electron.ipcRenderer.invoke("cash:open", payload),
  closeCashSession: (payload) => electron.ipcRenderer.invoke("cash:close", payload),
  listUsers: () => electron.ipcRenderer.invoke("users:list"),
  listProductsAdmin: () => electron.ipcRenderer.invoke("products:list-admin"),
  listProductCategories: () => electron.ipcRenderer.invoke("products:categories:list"),
  createProductRecord: (payload) => electron.ipcRenderer.invoke("products:create", payload),
  updateProductRecord: (payload) => electron.ipcRenderer.invoke("products:update", payload),
  deleteProductRecord: (id) => electron.ipcRenderer.invoke("products:delete", { id }),
  createProductCategory: (name) => electron.ipcRenderer.invoke("products:category:create", { name }),
  deleteProductCategory: (id) => electron.ipcRenderer.invoke("products:category:delete", { id }),
  createProductSubcategory: (payload) => electron.ipcRenderer.invoke("products:subcategory:create", payload),
  deleteProductSubcategory: (id) => electron.ipcRenderer.invoke("products:subcategory:delete", { id }),
  listCustomers: () => electron.ipcRenderer.invoke("customers:list"),
  createCustomer: (payload) => electron.ipcRenderer.invoke("customers:create", payload),
  updateCustomer: (payload) => electron.ipcRenderer.invoke("customers:update", payload),
  listSuppliers: () => electron.ipcRenderer.invoke("suppliers:list"),
  createSupplier: (payload) => electron.ipcRenderer.invoke("suppliers:create", payload),
  updateSupplier: (payload) => electron.ipcRenderer.invoke("suppliers:update", payload),
  listPurchases: () => electron.ipcRenderer.invoke("purchases:list"),
  getPurchaseDetail: (id) => electron.ipcRenderer.invoke("purchases:get-detail", { id }),
  createPurchase: (payload) => electron.ipcRenderer.invoke("purchases:create", payload),
  listInventoryMoves: () => electron.ipcRenderer.invoke("inventory:list"),
  listSales: (payload) => electron.ipcRenderer.invoke("sales:list", payload),
  getSaleDetail: (saleId) => electron.ipcRenderer.invoke("sales:get-detail", { saleId }),
  printSaleInvoice: (saleId) => electron.ipcRenderer.invoke("sales:print-invoice", { saleId })
});
